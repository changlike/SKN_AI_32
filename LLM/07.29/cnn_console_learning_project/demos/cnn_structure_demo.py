"""
CNN의 전체 구조와 각 계층의 역할을 콘솔에서 설명하는 모듈입니다.
"""


def run_cnn_structure_demo() -> None:
    """
    CNN의 특징 추출 영역과 분류 영역을 단계별로 출력합니다.
    """

    # 실습 제목을 출력합니다.
    print("\n[1. CNN 전체 구조 확인]")

    # CNN 전체 처리 흐름을 여러 줄 문자열로 정의합니다.
    architecture = """
입력 이미지
    ↓
합성곱 계층(Convolution)
    - 작은 커널을 이동시키며 지역 특징을 추출합니다.
    ↓
활성화 함수(ReLU)
    - 음수를 0으로 바꾸어 비선형성을 추가합니다.
    ↓
풀링 계층(Pooling)
    - 특성 맵의 가로와 세로 크기를 줄입니다.
    ↓
합성곱 블록 반복
    - 선과 경계를 객체의 부분 및 전체 특징으로 조합합니다.
    ↓
평탄화(Flatten) 또는 글로벌 평균 풀링
    - 추출한 특징을 분류 계층에 전달할 형태로 변환합니다.
    ↓
완전연결 계층(Fully Connected Layer)
    - 여러 특징을 종합하여 클래스별 점수를 계산합니다.
    ↓
출력 로짓(Logits)
    - 각 클래스에 대한 원시 점수를 출력합니다.
"""

    # 정의한 CNN 전체 구조를 콘솔에 출력합니다.
    print(architecture)

    # CNN의 핵심 원리를 설명하는 제목을 출력합니다.
    print("CNN의 핵심 원리")

    # 지역적 연결에 대한 설명을 출력합니다.
    print("1) 지역적 연결: 한 뉴런이 입력 전체가 아니라 작은 영역만 관찰합니다.")

    # 가중치 공유에 대한 설명을 출력합니다.
    print("2) 가중치 공유: 동일한 커널을 입력의 모든 위치에 반복 적용합니다.")

    # 계층적 특징 학습에 대한 설명을 출력합니다.
    print("3) 계층적 특징 학습: 단순한 특징을 조합하여 복잡한 특징을 만듭니다.")

    # 특징 학습 단계를 출력합니다.
    print("\n픽셀 → 선/경계 → 곡선/질감 → 객체의 부분 → 객체 전체 → 클래스")
